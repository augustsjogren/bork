fn art_lines() -> Vec<Line<'static>> {
    BONK_ART
        .iter()
        .map(|row| {
            let spans: Vec<Span<'static>> = row
                .iter()
                .map(|(top, bottom)| match (top, bottom) {
                    (Some((r, g, b)), Some((br, bg, bb))) => Span::styled(
                        "\u{2580}",
                        Style::default()
                            .fg(Color::Rgb(*r, *g, *b))
                            .bg(Color::Rgb(*br, *bg, *bb)),
                    ),
                    (Some((r, g, b)), None) => {
                        Span::styled("\u{2580}", Style::default().fg(Color::Rgb(*r, *g, *b)))
                    }
                    (None, Some((br, bg, bb))) => {
                        Span::styled("\u{2584}", Style::default().fg(Color::Rgb(*br, *bg, *bb)))
                    }
                    (None, None) => Span::raw(" "),
                })
                .collect();
            Line::from(spans)
        })
        .collect()
}

pub fn render_bonk(frame: &mut Frame, app: &App) {
    if app.input_mode != InputMode::Bonk {
        return;
    }

    let area = frame.area();
    let width = (ART_COLS as u16 + 2).min(area.width);
    let height = (ART_ROWS as u16 + 3).min(area.height); // +2 border, +1 footer
    let x = area.width.saturating_sub(width) / 2;
    let y = area.height.saturating_sub(height) / 2;
    let popup_area = Rect::new(x, y, width, height);

    frame.render_widget(Clear, popup_area);

    let block = Block::default()
        .borders(Borders::ALL)
        .border_style(Style::default().fg(styles::ACCENT))
        .title(Span::styled(
            " *BONK* ",
            Style::default()
                .fg(styles::ACCENT)
                .add_modifier(Modifier::BOLD),
        ));
    let inner = block.inner(popup_area);
    frame.render_widget(block, popup_area);

    if inner.height < 2 || inner.width < ART_COLS as u16 {
        return;
    }

    let art_area = Rect::new(
        inner.x,
        inner.y,
        inner.width,
        inner.height.saturating_sub(1),
    );
    frame.render_widget(Paragraph::new(art_lines()), art_area);

    let footer = Line::from(Span::styled("any key", styles::dim_style()));
    let footer_area = Rect::new(inner.x, inner.y + inner.height - 1, inner.width, 1);
    frame.render_widget(Paragraph::new(footer), footer_area);
}
